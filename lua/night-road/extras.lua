-- Theme files for other tools, generated from the variant palettes into
-- extras/. Regenerate with:
--   nvim --headless -u NONE --cmd "set rtp+=." -l scripts/extras.lua
local M = {}

local palettes = require("night-road.palette")
local terminal = require("night-road.terminal")

local function header(comment, variant)
	return ("%s night-road %s. Generated by scripts/extras.lua from palettes/%s.lua; do not edit."):format(
		comment,
		variant,
		variant
	)
end

--- Ghostty theme file: `theme = /path/to/extras/ghostty/night-road-<variant>`.
function M.ghostty(variant)
	local c = palettes.get(variant)
	local lines = {
		header("#", variant),
		"background = " .. c.bg,
		"foreground = " .. c.text,
		"cursor-color = " .. c.green,
		"cursor-text = " .. c.bg,
		"selection-background = " .. c.selection,
		"selection-foreground = " .. c.selection_fg,
	}

	for i, color in ipairs(terminal.colors(c)) do
		lines[#lines + 1] = ("palette = %d=%s"):format(i - 1, color)
	end

	return table.concat(lines, "\n") .. "\n"
end

--- tmux status bar, panes and messages: `source-file /path/to/extras/tmux/night-road-<variant>.tmux`.
function M.tmux(variant)
	local c = palettes.get(variant)
	local lines = {
		header("#", variant),
		('set -g status-style "bg=default,fg=%s"'):format(c.muted),
		"set -g status-left-length 40",
		('set -g status-left "#[bg=%s,fg=%s,bold] #S #[bg=default] "'):format(c.green, c.bg),
		('set -g status-right "#[fg=%s]#{b:pane_current_path}  #[fg=%s]%%H:%%M #[fg=%s]%%a "'):format(
			c.muted,
			c.teal,
			c.muted
		),
		('set -g window-status-format "#[fg=%s] #I #W "'):format(c.muted),
		('set -g window-status-current-format "#[bg=%s,fg=%s,bold] #I #W "'):format(c.surface, c.text),
		('set -g window-status-activity-style "fg=%s"'):format(c.amber),
		'set -g window-status-separator ""',
		('set -g pane-border-style "fg=%s"'):format(c.border),
		('set -g pane-active-border-style "fg=%s"'):format(c.green),
		('set -g message-style "bg=%s,fg=%s"'):format(c.surface, c.text),
		('set -g message-command-style "bg=%s,fg=%s"'):format(c.surface, c.teal),
		('set -g mode-style "bg=%s,fg=%s"'):format(c.selection, c.selection_fg),
	}

	return table.concat(lines, "\n") .. "\n"
end

-- Path (relative to the repository root) and renderer for every extra.
function M.files()
	local files = {}

	for _, variant in ipairs(palettes.variants) do
		files["extras/ghostty/night-road-" .. variant] = M.ghostty(variant)
		files["extras/tmux/night-road-" .. variant .. ".tmux"] = M.tmux(variant)
	end

	return files
end

return M
